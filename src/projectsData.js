// Helper to look up project by either standard id or legacy slug
export const getProjectById = (id) => {
  if (!id) return PROJECTS_DATA[0];
  const clean = id.toLowerCase().trim();
  if (clean === 'sree-sreenivasa-county' || clean === 'rrr-sree-sreenivasa-county') {
    return PROJECTS_DATA.find(p => p.id === 'rrr-sree-sreenivasa-county');
  }
  if (clean === 'sri-balaji-county' || clean === 'sri-balaji-county-balanagar') {
    return PROJECTS_DATA.find(p => p.id === 'sri-balaji-county');
  }
  if (clean === 'sree-laxmi-balaji-township') {
    return PROJECTS_DATA.find(p => p.id === 'sree-laxmi-balaji-township');
  }
  return PROJECTS_DATA.find(p => p.id === clean || p.slug === clean) || PROJECTS_DATA[0];
};

